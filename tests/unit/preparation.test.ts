const directories: string[] = [];
async function removeTemporaryDirectory(root: string): Promise<void> {
  for (let attempt = 0; ; attempt += 1) {
    try {
      // Do one removal attempt at a time: on Windows Sharp may still be closing
      // a WebP handle just after its promise resolves.
      await rm(root, { recursive: true, force: true, maxRetries: 0 });
      return;
    } catch (error) {
      const code = (error as NodeJS.ErrnoException).code;
      if (process.platform !== 'win32' || !['EBUSY', 'ENOTEMPTY', 'EPERM'].includes(code ?? '') || attempt === 19) throw error;
      await delay(250);
    }
  }
}
afterEach(async () => {
  // Retry only teardown; generated bytes and all production assertions are unchanged.
  await Promise.all(directories.splice(0).map(removeTemporaryDirectory));
}, 30_000);

async function put(root: string, name: string, bytes: Uint8Array | string): Promise<void> {
  const file = path.join(root, name);
  await mkdir(path.dirname(file), { recursive: true });
  await writeFile(file, bytes);
}

function pending<T>(value: T | null = null): Assessment<T> {
  return { value, confidence: 'unidentified', rationale: 'Synthetic test fixture.', evidence: [] };
}

function drawing(id: ArtworkRecord['id'], number: number): ArtworkRecord {
  return {
    id, sourceId: id, bookNumber: number, title: `Fixture ${number}`, publicDescription: 'Synthetic panes.',
    originalPhoto: pending('photo-002'), subjects: pending<string[]>(), location: pending<string>(), citations: [],
  };
}

function pixels(): Uint8Array {
  const result = new Uint8Array(11 * 11).fill(255);
  for (let y = 1; y <= 9; y += 1) for (let x = 1; x <= 9; x += 1) {
    if (x === 1 || x === 5 || x === 9 || y === 1 || y === 9) result[y * 11 + x] = 0;
  }
  return result;
}

async function drawingPng(compressionLevel = 9): Promise<Buffer> {
  return sharp(pixels(), { raw: { width: 11, height: 11, channels: 1 } })
    .toColourspace('b-w').png({ compressionLevel }).toBuffer();
}

function config(overrides: Partial<SegmentationConfig> = {}): SegmentationConfig {
  return { schemaVersion: 1, algorithmVersion: 'regions-v1', inkThreshold: 180, excludedSeedPoints: [[0, 0]], notes: 'Fixture settings.', ...overrides };
}

async function fixture(two = false): Promise<{ root: string; data: CatalogData }> {
  const root = await mkdtemp(path.join(tmpdir(), 'fcc preparation with spaces '));
  directories.push(root);
  const png = await drawingPng();
  const jpeg = await sharp({ create: { width: 80, height: 40, channels: 3, background: '#184ab2' } })
    .withMetadata({ orientation: 6 }).jpeg({ quality: 90 }).toBuffer();
  const photo: PhotoRecord = {
    id: 'photo-002', sourceId: 'photo-002', displayOrder: 1, coverage: 'whole-window',
    title: 'Fixture photograph', alt: 'Synthetic blue rectangle.', description: 'Synthetic source.',
    subjects: pending<string[]>(), location: pending<string>(), historicalEvidence: [],
  };
  const data: CatalogData = {
    project: { siteId: 'fixture', title: 'Fixture', projectVersion: '0.1.0', repositoryUrl: null, defaultBranch: 'main', releaseDateUtc: '2026-11-06T00:00:00.000Z' },
    manifest: { schemaVersion: 1, files: [
      { id: 'design-002', role: 'coloring', path: 'source/coloring/002.png', originalFilename: '002.png', bytes: png.byteLength, sha256: sha256Bytes(png), width: 11, height: 11, provenance: { sourceId: 'DRAWINGS', form: 'prepared-art' } },
      { id: 'photo-002', role: 'photo', path: 'source/photos/fixture photo.jpg', originalFilename: 'fixture photo.jpg', bytes: jpeg.byteLength, sha256: sha256Bytes(jpeg), width: 80, height: 40, provenance: { sourceId: 'PHOTOS', form: 'original-file' } },
    ] },
    photos: [photo], artworks: [drawing('design-002', 1)], subjects: [], sources: [], reviews: [],
    book: { schemaVersion: 1, title: 'Fixture', coverSourceId: 'cover', printableCoverSourceId: null, coverLines: ['Fixture'], intro: ['Fixture'], sourcesText: ['Fixture'], artworkOrder: ['design-002'], page: { width: 612, height: 792, margin: 36 }, layoutVersion: 'letter-v1', fontSourceId: 'font' },
    media: { schemaVersion: 1, photo: { maxLongEdge: 40, format: 'webp', quality: 90 }, thumbnail: { maxLongEdge: 10, format: 'webp', quality: 85 }, withoutEnlargement: true, algorithmVersion: 'web-images-v1' },
  };
  if (two) {
    data.artworks.push(drawing('design-003', 2));
    data.book.artworkOrder.push('design-003');
    data.manifest.files.push({ ...data.manifest.files[0]!, id: 'design-003', path: 'source/coloring/003.png', originalFilename: '003.png' });
    await put(root, 'source/coloring/003.png', png);
    await put(root, 'content/segmentation/design-003/config.json', jsonBytes(config()));
  }
  await put(root, 'source/coloring/002.png', png);
  await put(root, 'source/photos/fixture photo.jpg', jpeg);
  await put(root, 'source/manifest.json', jsonBytes(data.manifest));
  await put(root, 'content/artworks.json', jsonBytes({ schemaVersion: 1, artworks: data.artworks }));
  await put(root, 'content/media.json', jsonBytes(data.media));
  await put(root, 'content/segmentation/design-002/config.json', jsonBytes(config()));
  await put(root, 'generated/assets.json', jsonBytes({ schemaVersion: 1, artworks: {}, photos: {} }));
  return { root, data };
}

async function registry(root: string): Promise<AssetRegistry> {
  return AssetRegistrySchema.parse(JSON.parse(await readFile(path.join(root, 'generated/assets.json'), 'utf8')));
}

describe('preparation orchestration', () => {
  it('prepares photos only without touching drawing packages or segmentation settings', async () => {
    const { root, data } = await fixture();
    await put(root, 'content/segmentation/design-002/config.json', 'deliberately invalid segmentation config');
    const result = await prepareCatalogAssets(root, data, { all: true, photosOnly: true });
    expect(result.artworks).toEqual([]);
    expect(result.photos).toEqual(['photo-002']);
    expect((await registry(root)).artworks).toEqual({});
    expect(await readFile(path.join(root, 'content/segmentation/design-002/config.json'), 'utf8')).toBe('deliberately invalid segmentation config');
    await expect(stat(path.join(root, 'public/art'))).rejects.toMatchObject({ code: 'ENOENT' });
  });
  it('prepares complete measured packages, preserves source and authored bytes, and reruns without rewriting the registry', async () => {
    const { root, data } = await fixture();
    const sourceBefore = await readFile(path.join(root, 'source/coloring/002.png'));
    const authoredBefore = await readFile(path.join(root, 'content/artworks.json'));
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(first.artworks).toHaveLength(1);
    expect(first.artworks[0]).toMatchObject({ id: 'design-002', width: 11, height: 11, regionCount: 2, reusedPackage: false });
    expect(first.photos).toEqual([]);
    expect(first.skippedUnreviewedPhotoCandidates).toEqual(['design-002']);
    const assets = await registry(root);
    const version = assets.artworks['design-002']!.versions[first.artworks[0]!.contentVersion]!;
    const loaded = await readRegionPackage(root, 'design-002', version);
    expect(loaded.regions.map(region => region.pixelCount)).toEqual([21, 21]);
    expect(loaded.canonical).toEqual(pixels());
    const packageDirectory = path.posix.dirname(version.package.path);
    for (const filename of ['hit.bin', 'paint.bin', 'ink.bin']) {
      const compressed = await readFile(path.join(root, packageDirectory, filename));
      expect([...compressed.subarray(4, 8)]).toEqual([0, 0, 0, 0]);
    }
    expect(await readFile(path.join(root, 'source/coloring/002.png'))).toEqual(sourceBefore);
    expect(await readFile(path.join(root, 'content/artworks.json'))).toEqual(authoredBefore);
    const registryBytes = await readFile(path.join(root, 'generated/assets.json'));
    const registryTime = (await stat(path.join(root, 'generated/assets.json'))).mtimeMs;
    const second = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(second.artworks[0]).toMatchObject({ contentVersion: first.artworks[0]!.contentVersion, reusedPackage: true });
    expect(second.changedFiles).toEqual([]);
    expect(second.registryChanged).toBe(false);
    expect(await readFile(path.join(root, 'generated/assets.json'))).toEqual(registryBytes);
    expect((await stat(path.join(root, 'generated/assets.json'))).mtimeMs).toBe(registryTime);
    expect(await readdir(path.join(root, '.work/staging'))).toEqual([]);
    await expect(stat(path.join(root, 'content/reviews'))).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await readdir(path.join(root, first.artworks[0]!.reviewDirectory))).toContain('regions-numbered-2x.png');
  });

  it('keeps identity when notes, captions, exclusion order and unchanged mask filenames change', async () => {
    const { root, data } = await fixture();
    const zeroMask = await sharp(new Uint8Array(121), { raw: { width: 11, height: 11, channels: 1 } }).toColourspace('b-w').png().toBuffer();
    await put(root, 'content/segmentation/design-002/mask first.png', zeroMask);
    await put(root, 'content/segmentation/design-002/config.json', jsonBytes(config({ barrierAddMask: 'mask first.png', excludedSeedPoints: [[10, 10], [0, 0], [0, 0]] })));
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    await rename(path.join(root, 'content/segmentation/design-002/mask first.png'), path.join(root, 'content/segmentation/design-002/renamed mask.png'));
    await put(root, 'content/segmentation/design-002/config.json', jsonBytes(config({ barrierAddMask: 'renamed mask.png', excludedSeedPoints: [[0, 0], [10, 10]], notes: 'Editorial note only.' })));
    data.artworks[0]!.title = 'Edited caption';
    const second = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(second.artworks[0]!.contentVersion).toBe(first.artworks[0]!.contentVersion);
    expect(second.changedFiles).toEqual([]);
  });

  it('updates source freshness without replacing an immutable recipe for identical canonical pixels', async () => {
    const { root, data } = await fixture();
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    const before = await registry(root);
    const key = first.artworks[0]!.contentVersion;
    const priorVersion = before.artworks['design-002']!.versions[key]!;
    const frozen = await readFile(path.join(root, priorVersion.archiveRecipe!));
    const differentContainer = await drawingPng(0);
    const source = data.manifest.files[0]!;
    expect(sha256Bytes(differentContainer)).not.toBe(source.sha256);
    source.sha256 = sha256Bytes(differentContainer); source.bytes = differentContainer.byteLength;
    await put(root, source.path, differentContainer);
    const second = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(second.artworks[0]!.contentVersion).toBe(key);
    expect(second.artworks[0]!.reusedPackage).toBe(true);
    const after = await registry(root);
    const currentVersion = after.artworks['design-002']!.versions[key]!;
    expect(currentVersion.sourceDigest).toBe(source.sha256);
    expect(currentVersion.preparationDigest).not.toBe(priorVersion.preparationDigest);
    expect(currentVersion.package).toEqual(priorVersion.package);
    expect(await readFile(path.join(root, priorVersion.archiveRecipe!))).toEqual(frozen);
  });

  it('retains earlier versions and regenerates the current and archived maps from local recipes after outputs are removed', async () => {
    const { root, data } = await fixture();
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    const original = await registry(root);
    const oldKey = first.artworks[0]!.contentVersion;
    const oldVersion = original.artworks['design-002']!.versions[oldKey]!;
    const oldMaps = await readRegionPackage(root, 'design-002', oldVersion);
    await put(root, 'content/segmentation/design-002/config.json', jsonBytes(config({ inkThreshold: 190 })));
    const second = await prepareCatalogAssets(root, data, { id: 'design-002' });
    const newKey = second.artworks[0]!.contentVersion;
    expect(newKey).not.toBe(oldKey);
    expect(Object.keys((await registry(root)).artworks['design-002']!.versions)).toHaveLength(2);
    await rm(path.join(root, 'public/art'), { recursive: true });
    await rm(path.join(root, 'generated/assets.json'));
    const regenerated = await prepareCatalogAssets(root, data, { all: true, includeArchives: true });
    expect(regenerated.artworks).toHaveLength(2);
    expect(regenerated.artworks.find(item => item.contentVersion === oldKey)!.archive).toBe(true);
    const restored = await registry(root);
    expect(restored.artworks['design-002']!.activeVersion).toBe(newKey);
    const oldAgain = await readRegionPackage(root, 'design-002', restored.artworks['design-002']!.versions[oldKey]!);
    expect(oldAgain.hitLabels).toEqual(oldMaps.hitLabels);
    expect(oldAgain.paintLabels).toEqual(oldMaps.paintLabels);
    expect(oldAgain.inkAlpha).toEqual(oldMaps.inkAlpha);
    expect(oldAgain.canonical).toEqual(oldMaps.canonical);
  });

  it('does not reuse a corrupted existing package or overwrite its damaged bytes', async () => {
    const { root, data } = await fixture();
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    const assets = await registry(root);
    const version = assets.artworks['design-002']!.versions[first.artworks[0]!.contentVersion]!;
    const paintPath = path.join(root, path.posix.dirname(version.package.path), 'paint.bin');
    const damaged = await readFile(paintPath);
    damaged[damaged.length - 1] = damaged[damaged.length - 1]! ^ 1;
    await writeFile(paintPath, damaged);
    const registryBefore = await readFile(path.join(root, 'generated/assets.json'));
    await expect(prepareCatalogAssets(root, data, { id: 'design-002' })).rejects.toMatchObject({ code: 'E_ASSET_HASH' });
    expect(await readFile(paintPath)).toEqual(damaged);
    expect(await readFile(path.join(root, 'generated/assets.json'))).toEqual(registryBefore);
  });

  it('keeps the previous active registry and files when a later item in an all-design batch fails', async () => {
    const { root, data } = await fixture(true);
    await prepareCatalogAssets(root, data, { id: 'design-002' });
    const before = await readFile(path.join(root, 'generated/assets.json'));
    const previousDirectories = await readdir(path.join(root, 'public/art/design-002'));
    await put(root, 'content/segmentation/design-002/config.json', jsonBytes(config({ inkThreshold: 190 })));
    await put(root, 'content/segmentation/design-003/config.json', jsonBytes(config({ excludedSeedPoints: [[5, 1]] })));
    await expect(prepareCatalogAssets(root, data, { all: true })).rejects.toThrow(/design-003/);
    expect(await readFile(path.join(root, 'generated/assets.json'))).toEqual(before);
    expect(await readdir(path.join(root, 'public/art/design-002'))).toEqual(previousDirectories);
    await expect(stat(path.join(root, 'public/art/design-003'))).rejects.toMatchObject({ code: 'ENOENT' });
    expect(await readdir(path.join(root, '.work/staging'))).toEqual([]);
  });

  it('creates oriented web/thumbnail photos only after a current reviewed association in a selected run', async () => {
    const { root, data } = await fixture();
    data.artworks[0]!.originalPhoto.confidence = 'confirmed';
    const withoutReceipt = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(withoutReceipt.photos).toEqual([]);
    data.reviews.push({ schemaVersion: 1, recordId: 'design-002', reviewKind: 'photo-pairing', reviewedDigest: computeEditorialReviewDigest(data, 'design-002', 'photo-pairing'), reviewer: 'Synthetic fixture reviewer', reviewedAtUtc: '2026-11-06T00:00:00.000Z', outcome: 'complete' });
    const sourceBefore = await readFile(path.join(root, 'source/photos/fixture photo.jpg'));
    const prepared = await prepareCatalogAssets(root, data, { id: 'design-002' });
    expect(prepared.photos).toEqual(['photo-002']);
    const record = (await registry(root)).photos['photo-002']!;
    expect(record).toMatchObject({ width: 20, height: 40 });
    // Inspect bytes rather than path-backed Sharp inputs so Windows can release
    // the derivative files before the fixture teardown removes the directory.
    const web = await sharp(await readFile(path.join(root, record.web.path))).metadata();
    const thumbnail = await sharp(await readFile(path.join(root, record.thumbnail.path))).metadata();
    expect(web).toMatchObject({ width: 20, height: 40, format: 'webp' });
    expect(thumbnail).toMatchObject({ width: 5, height: 10, format: 'webp' });
    expect(await readFile(path.join(root, 'source/photos/fixture photo.jpg'))).toEqual(sourceBefore);
    expect((await prepareCatalogAssets(root, data, { id: 'design-002' })).changedFiles).toEqual([]);
  });

  it('fails before promotion when source bytes or frozen archive inputs no longer match their receipts', async () => {
    const { root, data } = await fixture();
    const first = await prepareCatalogAssets(root, data, { id: 'design-002' });
    const before = await readFile(path.join(root, 'generated/assets.json'));
    const source = data.manifest.files[0]!;
    const original = await readFile(path.join(root, source.path));
    await put(root, source.path, Buffer.from('not the recorded drawing'));
    await expect(prepareCatalogAssets(root, data, { id: 'design-002' })).rejects.toMatchObject({ code: 'E_PREPARATION_SOURCE' });
    await put(root, source.path, original);
    const version = (await registry(root)).artworks['design-002']!.versions[first.artworks[0]!.contentVersion]!;
    const frozenMask = path.posix.join(path.posix.dirname(version.archiveRecipe!), 'domain.bin');
    await put(root, frozenMask, new Uint8Array(121));
    await expect(prepareCatalogAssets(root, data, { id: 'design-002' })).rejects.toMatchObject({ code: 'E_IMMUTABLE_COLLISION' });
    expect(await readFile(path.join(root, 'generated/assets.json'))).toEqual(before);
  });
});
